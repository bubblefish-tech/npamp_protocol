package hybridkem_test

// hybridkem_kat_test.go grades the standalone adapter (non-circular):
// the X25519MLKEM768 combiner's output is checked against standards-anchored
// expected values (NIST ACVP FIPS 203, RFC 7748 section 6.1 — the same anchors
// kemwire_kat_test.go uses, reused here rather than re-derived) and is
// separately cross-checked byte-identical against the root package's
// SharedSecrets.Combined() for the SAME real key-exchange inputs, so the
// extraction cannot silently diverge from the reference it was extracted from.
// The SecP384r1MLKEM1024 group (0x11ed) is graded as a REFUSAL: Combine returns
// ErrGroupNotSupported and no output (TestCombineRefusesSecP384r1MLKEM1024).

import (
	"bytes"
	"crypto/ecdh"
	"encoding/hex"
	"encoding/json"
	"errors"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"testing"

	npamp "github.com/bubblefish-tech/npamp_protocol/impl/go"
	"github.com/bubblefish-tech/npamp_protocol/impl/go/hybridkem"
)

// katDir is the pinned, language-agnostic test-vector corpus, relative to
// impl/go/hybridkem. The files under it are frozen (MANIFEST.sha256) and
// MUST NOT be regenerated by an implementation under test.
var katDir = filepath.Join("..", "..", "..", "test-vectors", "v1")

func loadKAT(t *testing.T, name string, v any) {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join(katDir, name))
	if err != nil {
		t.Fatalf("read KAT %s: %v", name, err)
	}
	if err := json.Unmarshal(raw, v); err != nil {
		t.Fatalf("parse KAT %s: %v", name, err)
	}
}

func mustHex(t *testing.T, field, s string) []byte {
	t.Helper()
	b, err := hex.DecodeString(s)
	if err != nil {
		t.Fatalf("hex field %s: %v", field, err)
	}
	return b
}

func mustHexU16(t *testing.T, field, s string) uint16 {
	t.Helper()
	n, err := strconv.ParseUint(strings.TrimPrefix(s, "0x"), 16, 16)
	if err != nil {
		t.Fatalf("hex code point %s = %q: %v", field, s, err)
	}
	return uint16(n)
}

func concat(a, b []byte) []byte {
	out := make([]byte, 0, len(a)+len(b))
	out = append(out, a...)
	return append(out, b...)
}

// kemWireKAT mirrors test-vectors/v1/kem-wire-kat.json (the same struct shape
// as ../kemwire_kat_test.go's kemWireKAT), standards-derived (NIST ACVP FIPS
// 203; RFC 7748 section 6.1), non-circular.
type kemWireKAT struct {
	KEMCodepoint string `json:"kem_codepoint"`
	Keygen       struct {
		D  string `json:"d"`
		Z  string `json:"z"`
		EK string `json:"ek"`
	} `json:"mlkem768_keygen"`
	X25519 struct {
		AlicePrivate string `json:"alice_private"`
		AlicePublic  string `json:"alice_public"`
		BobPrivate   string `json:"bob_private"`
		BobPublic    string `json:"bob_public"`
		SharedSecret string `json:"shared_secret"`
	} `json:"x25519_rfc7748_6_1"`
	DecapsRef struct {
		SharedSecretK string `json:"shared_secret_K"`
	} `json:"mlkem768_decaps_reference"`
	WireLayout struct {
		KEMShareLen       int `json:"kem_share_len"`
		KEMCiphertextLen  int `json:"kem_ciphertext_len"`
		CombinedSecretLen int `json:"combined_secret_len"`
	} `json:"wire_layout"`
}

// TestCombineX25519MLKEM768_RFCAnchored pins the ML-KEM-first order directly
// against the standards-anchored values kem-wire-kat.json carries: the NIST
// ACVP FIPS 203 ML-KEM-768 decapsulation-reference shared secret and the RFC
// 7748 section 6.1 X25519 shared secret. Neither value is generated by this
// package or by the npamp reference implementation.
func TestCombineX25519MLKEM768_RFCAnchored(t *testing.T) {
	var kat kemWireKAT
	loadKAT(t, "kem-wire-kat.json", &kat)

	if got := mustHexU16(t, "kem_codepoint", kat.KEMCodepoint); hybridkem.Group(got) != hybridkem.X25519MLKEM768 {
		t.Fatalf("kem_codepoint = 0x%04x, want 0x%04x", got, uint16(hybridkem.X25519MLKEM768))
	}

	kNIST := mustHex(t, "shared_secret_K", kat.DecapsRef.SharedSecretK) // NIST ACVP FIPS 203 anchor
	xss := mustHex(t, "shared_secret", kat.X25519.SharedSecret)        // RFC 7748 section 6.1 anchor

	got, err := hybridkem.Combine(hybridkem.X25519MLKEM768, kNIST, xss)
	if err != nil {
		t.Fatalf("Combine(X25519MLKEM768): %v", err)
	}
	if len(got) != kat.WireLayout.CombinedSecretLen || len(got) != hybridkem.CombinedSecretSizeX25519MLKEM768 {
		t.Fatalf("combined secret len = %d, want %d", len(got), kat.WireLayout.CombinedSecretLen)
	}
	if !bytes.Equal(got, concat(kNIST, xss)) {
		t.Fatal("Combine(X25519MLKEM768) is not ML-KEM_ss || X25519_ss")
	}
	if bytes.Equal(got, concat(xss, kNIST)) {
		t.Fatal("Combine(X25519MLKEM768) unexpectedly also matches the reversed (X25519-first) order")
	}
}

// TestCombineX25519MLKEM768_CrossCheck drives the REAL X25519MLKEM768
// exchange through the root npamp package (whose values are themselves
// anchored to RFC 7748 section 6.1 and NIST ACVP by ../kemwire_kat_test.go)
// and asserts hybridkem.Combine on the raw component secrets is byte-
// identical to SharedSecrets.Combined() for the same inputs.
func TestCombineX25519MLKEM768_CrossCheck(t *testing.T) {
	var kat kemWireKAT
	loadKAT(t, "kem-wire-kat.json", &kat)

	seed := concat(mustHex(t, "d", kat.Keygen.D), mustHex(t, "z", kat.Keygen.Z))
	alicePriv := mustHex(t, "alice_private", kat.X25519.AlicePrivate)
	bobPriv := mustHex(t, "bob_private", kat.X25519.BobPrivate)

	client, err := npamp.NewKEMClient(seed, alicePriv)
	if err != nil {
		t.Fatal(err)
	}
	bob, err := ecdh.X25519().NewPrivateKey(bobPriv)
	if err != nil {
		t.Fatal(err)
	}
	share := client.KEMShare()
	ct, serverSS, err := npamp.EncapsulateWith(share, bob)
	if err != nil {
		t.Fatal(err)
	}
	clientSS, err := client.SharedSecrets(ct)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(clientSS.MLKEM, serverSS.MLKEM) || !bytes.Equal(clientSS.X25519, serverSS.X25519) {
		t.Fatal("client/server component shared secrets disagree (exchange broken, not an adapter issue)")
	}

	adapterOut, err := hybridkem.Combine(hybridkem.X25519MLKEM768, clientSS.MLKEM, clientSS.X25519)
	if err != nil {
		t.Fatalf("Combine(X25519MLKEM768): %v", err)
	}
	refOut := clientSS.Combined()
	if !bytes.Equal(adapterOut, refOut) {
		t.Fatalf("hybridkem.Combine diverges from npamp.SharedSecrets.Combined(): got %x, want %x", adapterOut, refOut)
	}
}

// TestCombineRefusesSecP384r1MLKEM1024 pins the refusal of the 0x11ed group: Combine returns
// ErrGroupNotSupported and no output, whatever the component secrets are. It runs every size
// pairing a caller could pass (the sizes the group's components would have, X25519-sized,
// empty, nil), because a refusal that held only for malformed input would still combine a
// well-formed one. The group's code point stays defined so callers can name it.
func TestCombineRefusesSecP384r1MLKEM1024(t *testing.T) {
	if uint16(hybridkem.SecP384r1MLKEM1024) != 0x11ed {
		t.Fatalf("SecP384r1MLKEM1024 = %#04x, want the 0x11ed code point", uint16(hybridkem.SecP384r1MLKEM1024))
	}
	mlkemSS := bytes.Repeat([]byte{0xa5}, hybridkem.MLKEMSharedSecretSize)
	cases := []struct {
		name      string
		mlkem     []byte
		classical []byte
	}{
		{"p384-sized classical secret", mlkemSS, bytes.Repeat([]byte{0x5a}, 48)},
		{"x25519-sized classical secret", mlkemSS, bytes.Repeat([]byte{0x5a}, hybridkem.X25519SharedSecretSize)},
		{"empty classical secret", mlkemSS, []byte{}},
		{"nil classical secret", mlkemSS, nil},
		{"short ML-KEM secret", mlkemSS[:31], bytes.Repeat([]byte{0x5a}, 48)},
		{"nil ML-KEM secret", nil, bytes.Repeat([]byte{0x5a}, 48)},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got, err := hybridkem.Combine(hybridkem.SecP384r1MLKEM1024, c.mlkem, c.classical)
			if !errors.Is(err, hybridkem.ErrGroupNotSupported) {
				t.Fatalf("Combine(SecP384r1MLKEM1024) err = %v, want ErrGroupNotSupported", err)
			}
			if got != nil {
				t.Fatalf("Combine(SecP384r1MLKEM1024) returned %d octets alongside the refusal, want nil", len(got))
			}
		})
	}
	// The refusal is specific to that group: the other defined group still combines, and an
	// undefined code point is still ErrUnknownGroup rather than ErrGroupNotSupported.
	if _, err := hybridkem.Combine(hybridkem.X25519MLKEM768, mlkemSS, bytes.Repeat([]byte{0x5a}, hybridkem.X25519SharedSecretSize)); err != nil {
		t.Fatalf("Combine(X25519MLKEM768) after the refusal change: %v", err)
	}
	if _, err := hybridkem.Combine(hybridkem.Group(0xffff), mlkemSS, mlkemSS); !errors.Is(err, hybridkem.ErrUnknownGroup) {
		t.Fatalf("Combine(0xffff) err = %v, want ErrUnknownGroup", err)
	}
}

// TestCombineErrors exercises the adapter's input-validation surface for the supported
// group: an unknown group and wrong-length component secrets must be rejected, never
// silently truncated or padded.
func TestCombineErrors(t *testing.T) {
	mlkemSS := make([]byte, hybridkem.MLKEMSharedSecretSize)
	x25519SS := make([]byte, hybridkem.X25519SharedSecretSize)

	if _, err := hybridkem.Combine(hybridkem.Group(0xffff), mlkemSS, x25519SS); err != hybridkem.ErrUnknownGroup {
		t.Fatalf("unknown group: err = %v, want %v", err, hybridkem.ErrUnknownGroup)
	}
	if _, err := hybridkem.Combine(hybridkem.X25519MLKEM768, mlkemSS[:31], x25519SS); err != hybridkem.ErrMLKEMSecretSize {
		t.Fatalf("short ML-KEM secret: err = %v, want %v", err, hybridkem.ErrMLKEMSecretSize)
	}
	if _, err := hybridkem.Combine(hybridkem.X25519MLKEM768, mlkemSS, x25519SS[:31]); err != hybridkem.ErrClassicalSecretSize {
		t.Fatalf("short X25519 secret: err = %v, want %v", err, hybridkem.ErrClassicalSecretSize)
	}
}
