// assertReject fails the test unless err is a *RejectError with the given
// Reason -- proving both that the call actually rejected (not merely
// returned some unrelated error) and that it named the RIGHT reason (a
// stub that always returns the same RejectReason would fail this on every
// case but one, which is exactly the point).
func assertReject(t *testing.T, err error, want RejectReason) {
	t.Helper()
	if err == nil {
		t.Fatalf("got nil error, want a *RejectError with reason %q", want)
	}
	var re *RejectError
	if !errors.As(err, &re) {
		t.Fatalf("got error %v (%T), want a *RejectError with reason %q", err, err, want)
	}
	if re.Reason != want {
		t.Fatalf("got RejectError reason %q, want %q (detail: %s)", re.Reason, want, re.Detail)
	}
}
