// TestValidateTLVSequence_RejectsOverBoundsTLVCount: npamp.MaxTLVsPerFrame
// (tlv.go) is the frozen cap of 64; a hand-constructed slice of 65
// registered TLVs (bypassing npamp.DecodeTLVs, which would itself stop at
// the same bound) proves this validator's OWN defense-in-depth check works
// independent of DecodeTLVs.
func TestValidateTLVSequence_RejectsOverBoundsTLVCount(t *testing.T) {
	reg := testRegistries(t)
	tlvs := make([]npamp.TLV, npamp.MaxTLVsPerFrame+1)
	for i := range tlvs {
		tlvs[i] = npamp.TLV{Type: npamp.TLVProfileOffer, Value: []byte{0x01}}
	}
	err := reg.ValidateTLVSequence(tlvs)
	assertReject(t, err, ReasonTooManyTLVs)
}

